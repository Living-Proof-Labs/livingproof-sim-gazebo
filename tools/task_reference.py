"""Generate only the repository's reviewed public Task interfaces, without running tasks."""

import json
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def capture(*args):
    # Task summaries show only environment assignments not already inherited.
    # Keep the reviewed Taskfile's declaration visible in either execution context.
    env = {
        key: value
        for key, value in os.environ.items()
        if key not in {"UV_PYTHON_DOWNLOADS", "UV_SYSTEM_CERTS", "LIVINGPROOF_TOOLING"}
    }
    env["VERSION"] = "0.0.0"
    return subprocess.check_output(
        [args[0], "--color=false", *args[1:]], cwd=ROOT, text=True, env=env
    ).strip()


def render():
    version = capture("task", "--version")
    if "3.54.0" not in version:
        raise SystemExit("Task reference requires pinned Task 3.54.0")
    lines = [
        "# Contributor tasks",
        "",
        "Generated by `task docs:reference` from native Task 3.54.0 listing and summaries.",
        "Do not edit this reference by hand. These commands describe reviewed repository",
        "Taskfiles; generation does not execute task bodies. Examples use `VERSION=0.0.0`",
        "as a placeholder, not a package release claim.",
        "",
        "Ordinary commands run directly inside the development image (LIVINGPROOF_TOOLING=1).",
        "On the host they use Docker and Task. Explicit prepared-environment commands remain available.",
        "",
    ]
    for filename, title in [
        ("Taskfile.yml", "Host"),
        ("Taskfile.runtime.yml", "Prepared environment"),
    ]:
        lines += ["## " + title, ""]
        tasks = json.loads(capture("task", "-t", filename, "--list", "--json"))["tasks"]
        for task in tasks:
            name = task["name"]
            prefix = "task" if filename == "Taskfile.yml" else "task -t Taskfile.runtime.yml"
            summary = capture("task", "-t", filename, "--summary", name)
            lines += [f"### `{prefix} {name}`", "", "```text", summary, "```", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    content = render()
    path = ROOT / "docs/tasks.md"
    if "--check" in sys.argv:
        if not path.exists() or path.read_text() != content:
            raise SystemExit("Task reference is stale. Run task docs:reference.")
    else:
        path.write_text(content)
