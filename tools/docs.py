"""Generate command reference from the actual parser."""
from pathlib import Path
import sys

from livingproof_sim_gazebo.cli import parser

path = Path("docs/command.md")
content = "# Command reference\n\nGenerated by `task docs:reference`.\n\n```text\n" + parser().format_help() + "```\n"
if "--check" in sys.argv:
    if not path.exists() or path.read_text() != content:
        raise SystemExit("Command reference is stale; run task docs:reference")
else:
    path.write_text(content)
